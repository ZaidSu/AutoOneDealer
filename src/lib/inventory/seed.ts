/** The same cars written the way the website's pages read when copied, so the pasted-text import can load them. */
export function seedText(): string {
  const lines = [`Results 1 - ${SEED.length} of ${SEED.length}`];
  for (const [header, title, price, miles] of SEED) {
    lines.push(`${header} for sale at Auto One Motors in Garland TX`, title, "Price", price == null ? "Sold" : `$${price.toLocaleString("en-US")}`, "Mileage", miles.toLocaleString("en-US"));
  }
  return lines.join("\n");
}
